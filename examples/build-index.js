#!env node
// Generates examples/INDEX.md, a single index page linking to every
// generated example. Run `node examples/build-index.js` after adding a
// new example script to this array to pick it up.
//
// This is the "regenerate everything" entry point: `npm run examples`
// runs every generator script below (in order) and then this one.

