#!env node
// Generates examples/FeatureShowcase.md by calling every function the
// module exports. Run with `node examples/feature-showcase.js` to
// regenerate the file after changing src/.

const fs = require('fs')
const path = require('path')
const markdown = require('../src/index.js')

let doc = ''

doc += `[${markdown.link('Back to examples', './README.md')}]\n`
doc += markdown.hr()
doc += markdown.h1('Feature Showcase')
doc += 'This page is generated by `examples/feature-showcase.js` and exercises every function `mr_markdown_builder` exports. Regenerate it with `node examples/feature-showcase.js` whenever the module changes.\n'

doc += markdown.h2('Headers')
doc += markdown.h1('h1 header') +
  markdown.h2('h2 header') +
  markdown.h3('h3 header') +
  markdown.h4('h4 header') +
  markdown.h5('h5 header') +
  markdown.h6('h6 header') +
  markdown.hX(9, 'hX(9, ...) clamps to h6')

doc += markdown.h2('Emphasis')
doc += markdown.ul([
  `${markdown.b('bold')} via b()`,
  `${markdown.i('italic')} via i()`,
  `${markdown.s('strikethrough')} via s()`,
  `${markdown.ic('inline code')} via ic()`,
])
doc += markdown.cb('const codeBlock = "via cb()"')
doc += '\n'

doc += markdown.h2('Lists')
doc += markdown.h3('Unordered (ul)')
doc += markdown.ul(['First item', 'Second item'])
doc += markdown.h3('Ordered (ol), with a callback')
doc += markdown.ol(['first item', 'second item'], (item) => item.toUpperCase())
doc += markdown.h3('Task list (tl), mixing plain strings and checked items')
doc += markdown.tl([
  'Plain string items render unchecked',
  { text: 'Explicitly unchecked', checked: false },
  { text: 'Explicitly checked', checked: true },
])

doc += markdown.h2('Tables')
doc += markdown.h3('Default (unaligned) columns')
doc += markdown.tableHeader(['Left', 'Center', 'Right']) + '\n' +
  markdown.tableRows([
    ['a', 'b', 'c'],
    ['d', 'e', 'f'],
  ])
doc += markdown.h3('Per-column alignment')
doc += markdown.tableHeader(['Left', 'Center', 'Right'], ['left', 'center', 'right']) + '\n' +
  markdown.tableRows([
    ['a', 'b', 'c'],
    ['d', 'e', 'f'],
  ])

doc += markdown.h2('Miscellaneous')
doc += markdown.h3('Links and images')
doc += markdown.ul([
  markdown.link('Explicit URL', 'https://github.com/mediumroast/mr_markdown_builder'),
  markdown.link('Falls back to an anchor when url is null', null),
  markdown.image('placeholder image', 'https://placehold.co/80x40', 'a placeholder'),
  markdown.imageWithSize('placeholder image, fixed height', 'https://placehold.co/80x40', 40),
])
doc += markdown.h3('Quote (multi-line)')
doc += markdown.quote('Every line of this string\nis prefixed with a blockquote marker.') + '\n'
doc += markdown.h3('Badges and tags')
doc += markdown.badge('build', 'passing', 'brightgreen') + ' ' + markdown.tag('example') + '\n'
doc += markdown.h3('Collapsible section')
doc += markdown.collapsible('Click to expand', 'Hidden content lives here.')
doc += markdown.h3('Arrows and whitespace helpers')
doc += `${markdown.upArrow()} ${markdown.downArrow()} ${markdown.leftArrow()} ${markdown.rightArrow()}${markdown.space()}(space helper before this text)${markdown.cr()}`
doc += markdown.h3('Text-level HTML: ins, sub, sup, and a hard break via br()')
doc += `${markdown.ins('underlined')} ${markdown.sub('sub')} ${markdown.sup('sup')}${markdown.br()}`
doc += 'This line follows a hard break.\n'
doc += markdown.h3('GitHub shorthand: mention, issueRef, emoji, colorSwatch')
doc += `${markdown.mention('octocat')} ${markdown.issueRef(42)} ${markdown.emoji('tada')} ${markdown.colorSwatch('#1d9bf0')}\n`
doc += markdown.h3('Math: mathInline and mathBlock')
doc += `${markdown.mathInline('E = mc^2')}\n`
doc += markdown.mathBlock('\\sum_{i=1}^{n} i = \\frac{n(n+1)}{2}') + '\n'
doc += markdown.h3('comment (renders nothing visible)')
doc += markdown.comment('This is only visible in the raw markdown source.') + '\n'
doc += markdown.h3('namedAnchor (a manual, non-heading anchor point)')
doc += markdown.namedAnchor('showcase-anchor') + `Linkable via ${markdown.link('#showcase-anchor', '#showcase-anchor')}\n`

doc += markdown.h2('GeoJSON / TopoJSON code blocks')
doc += markdown.geojson({
  type: 'Feature',
  geometry: { type: 'Point', coordinates: [-117.078046, 32.934771] },
  properties: { name: 'Example point' },
})
doc += '\n'
doc += markdown.topojson({ type: 'Topology', objects: {}, arcs: [] })
doc += '\n'

const outPath = path.join(__dirname, 'FeatureShowcase.md')
fs.writeFileSync(outPath, doc)
console.log(`Wrote ${outPath}`)
