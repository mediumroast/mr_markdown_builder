#!env node
// Generates examples/HeadersAndEmphasis.md. Self-contained: run
// `node examples/headers-and-emphasis.js` from anywhere to regenerate it.

const fs = require('fs')
const path = require('path')
const markdown = require('../src/index.js')

let doc = ''
doc += `[${markdown.link('Back to examples index', './INDEX.md')}]\n`
doc += markdown.hr()
doc += markdown.h1('Headers & Emphasis')
doc += 'Generated by `examples/headers-and-emphasis.js`, covering `h1`-`h6`, `hX`, and every emphasis helper.\n'

doc += markdown.h2('Headers')
doc += markdown.h1('h1: The Document Title') +
  markdown.h2('h2: A Major Section') +
  markdown.h3('h3: A Subsection') +
  markdown.h4('h4: A Detail') +
  markdown.h5('h5: A Fine Detail') +
  markdown.h6('h6: The Finest Detail')
doc += markdown.h2('hX with an explicit level')
doc += markdown.hX(3, 'hX(3, ...) is identical to h3(...)')
doc += markdown.hX(20, 'hX(20, ...) clamps down to h6, since markdown has no level-20 header')

doc += markdown.h2('Emphasis')
doc += markdown.ul([
  `${markdown.b('b()')} renders ${markdown.b('bold text')}`,
  `${markdown.b('i()')} renders ${markdown.i('italic text')}`,
  `${markdown.b('s()')} renders ${markdown.s('strikethrough text')}`,
  `${markdown.b('ic()')} renders ${markdown.ic('inline code')}`,
])
doc += markdown.h3('cb() for a fenced code block')
doc += markdown.cb('function greet(name) {\n  return `Hello, ${name}!`\n}')

const outPath = path.join(__dirname, 'HeadersAndEmphasis.md')
fs.writeFileSync(outPath, doc)
console.log(`Wrote ${outPath}`)
