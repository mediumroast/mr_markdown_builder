#!env node
// Generates examples/LinksAndMedia.md. Self-contained: run
// `node examples/links-and-media.js` from anywhere to regenerate it.
//
// Every URL and image referenced here is a stable, public target
// (GitHub itself, or shields.io/placehold.co placeholder generators),
// so none of the links in the generated output are dangling.

const fs = require('fs')
const path = require('path')
const markdown = require('../src/index.js')

let doc = ''
doc += `[${markdown.link('Back to examples index', './INDEX.md')}]\n`
doc += markdown.hr()
doc += markdown.h1('Links, Images & Miscellaneous')
doc += 'Generated by `examples/links-and-media.js`, covering `link`, `image`, `imageWithSize`, `anchor`, `namedAnchor`, `quote`, `alert`, `footnoteRef`/`footnoteDefs`, `badge`, `tag`, `collapsible`, `ins`/`sub`/`sup`, `br`, `mention`, `issueRef`, `emoji`, `colorSwatch`, `mathInline`/`mathBlock`, `comment`, and the small formatting helpers.\n'

doc += markdown.namedAnchor('top')

doc += markdown.h2('Links')
doc += markdown.ul([
  markdown.link('This repository', 'https://github.com/mediumroast/mr_markdown_builder'),
  `${markdown.link('A link with no explicit url', null)} falls back to an in-page anchor built from its title`,
])

doc += markdown.h2('Images')
doc += markdown.image('placeholder image', 'https://placehold.co/120x60', 'a 120x60 placeholder') + '\n'
doc += 'A fixed-height variant, for when a raw markdown image tag can\'t control size:\n'
doc += markdown.imageWithSize('placeholder image, fixed height', 'https://placehold.co/120x60', 30)

doc += markdown.h2('Anchor')
doc += `\`anchor('${markdown.i('A Header With Special Characters!')}')\` → \`${markdown.anchor('A Header With Special Characters!')}\`\n`

doc += markdown.h2('Quote')
doc += 'Every line of a multi-line string gets its own blockquote marker:\n'
doc += markdown.quote('First line of the quote.\nSecond line of the quote.')

doc += markdown.h2('GitHub Alerts')
doc += 'A blockquote whose first line is a `[!TYPE]` marker; type must be one of NOTE, TIP, IMPORTANT, WARNING, or CAUTION:\n'
doc += markdown.alert('NOTE', 'Highlights information that users should take into account, even when skimming.') + '\n'
doc += markdown.alert('WARNING', 'Urgent info that needs immediate attention to avoid problems.') + '\n'

doc += markdown.h2('Footnotes')
doc += `This library ships as a fork of the archived markdown-builder${markdown.footnoteRef('fork')}, with a few enhancements of its own${markdown.footnoteRef('features')}.\n`
doc += 'Reference a footnote inline with `footnoteRef(id)`; render all of the definitions together, wherever you want them to appear, with `footnoteDefs(entries)`. There\'s no auto-numbering -- you supply each id.\n'

doc += markdown.h2('Badges & tags')
doc += markdown.badge('tests', 'passing', 'brightgreen') + ' ' +
  markdown.badge('license', 'MIT', 'blue') + ' ' +
  markdown.tag('markdown') + ' ' +
  markdown.tag('example')
doc += '\n'

doc += markdown.h2('Collapsible section')
doc += markdown.collapsible('Click to expand', 'This content is hidden until the reader expands the section.')

doc += markdown.h2('Arrows and whitespace helpers')
doc += `${markdown.upArrow()} up, ${markdown.downArrow()} down, ${markdown.leftArrow()} left, ${markdown.rightArrow()} right${markdown.space()}(a non-breaking space before this text, from space())${markdown.cr()}`

doc += markdown.h2('Text-level HTML helpers')
doc += `${markdown.ins('underlined')}, ${markdown.sub('subscript')}, and ${markdown.sup('superscript')} all render via their HTML tags, since GFM has no dedicated syntax for them.${markdown.br()}`
doc += `This line ends with a hard break from ${markdown.ic('br()')}, so this text starts on a new line without a blank paragraph between them.\n`

doc += markdown.h2('GitHub-specific shorthand')
doc += markdown.ul([
  `${markdown.ic("mention('octocat')")} → ${markdown.mention('octocat')}`,
  `${markdown.ic('issueRef(42)')} → ${markdown.issueRef(42)}`,
  `${markdown.ic("emoji('tada')")} → ${markdown.emoji('tada')}`,
  `${markdown.ic("colorSwatch('#1d9bf0')")} → ${markdown.colorSwatch('#1d9bf0')} (GitHub renders a swatch next to a valid hex/rgb/hsl value)`,
])

doc += markdown.h2('Math')
doc += `Inline: ${markdown.mathInline('E = mc^2')}\n`
doc += markdown.mathBlock('\\sum_{i=1}^{n} i = \\frac{n(n+1)}{2}') + '\n'

doc += markdown.h2('Comments')
doc += `${markdown.comment('This paragraph is invisible in the rendered output.')}\nComments render nothing in this spot; view the raw markdown to see it.\n`

doc += markdown.hr()
doc += markdown.footnoteDefs([
  { id: 'fork', text: `See ${markdown.link('Chalarangelo/markdown-builder', 'https://github.com/Chalarangelo/markdown-builder')}, now archived.` },
  { id: 'features', text: 'Tables, GitHub alerts, checked task items, aligned columns, nested lists, footnotes, math, and more --\nsome definitions span multiple lines, and the continuation stays indented under the marker.' },
])
doc += '\n'

doc += markdown.h2('Back to top')
doc += `${markdown.link('Jump to the top of this page', '#top')}\n`

const outPath = path.join(__dirname, 'LinksAndMedia.md')
fs.writeFileSync(outPath, doc)
console.log(`Wrote ${outPath}`)
